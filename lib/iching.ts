export function yaoSymbol(y: Yao): string {
  if (y.value === 6) return "⚋ ×"; // 老陰（変）
  if (y.value === 9) return "⚊ ○"; // 老陽（変）
  if (y.value === 7) return "⚊";
  return "⚋";
}
