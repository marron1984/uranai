export function getSunSign(month: number, day: number): Zodiac {
  for (const r of RANGES) {
    const [fm, fd] = r.from;
    const [tm, td] = r.to;
    if (fm === tm) {
      if (month === fm && day >= fd && day <= td) {
        return ZODIAC.find((z) => z.key === r.key)!;
      }
    } else if (fm < tm) {
      if (
        (month === fm && day >= fd) ||
        (month === tm && day <= td) ||
        (month > fm && month < tm)
      ) {
        return ZODIAC.find((z) => z.key === r.key)!;
      }
    } else {
      // 山羊座（年をまたぐ）
      if (
        (month === fm && day >= fd) ||
        (month === tm && day <= td) ||
        month > fm ||
        month < tm
      ) {
        return ZODIAC.find((z) => z.key === r.key)!;
      }
    }
  }
  return ZODIAC[0];
}

