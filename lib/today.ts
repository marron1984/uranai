export type TodayOneLiner = {
  line: string;          // メインの一言
  flavor: string | null; // 通変星フレーバー (任意)
  reading: string;       // 算出根拠 (PD2 × 傷官 × 辛亥 のような)
};

export function todayOneLiner(date: Date = new Date()): TodayOneLiner {
  const y = date.getFullYear();
  const m = date.getMonth() + 1;
  const d = date.getDate();
  const pd = personalDay(OWNER.birth, y, m, d);
  const dp = todayDayPillar(date);
  const tb = todayTongbianForOwner(date);

  const variants = ONE_LINER_VARIANTS[pd] ?? ONE_LINER_VARIANTS[1];
  const line = pickByDate(variants, date, 701);

  // 通変星フレーバーがあれば常時表示
  const flavorArr = TONGBIAN_FLAVOR[tb.star];
  const flavor = flavorArr ? pickByDate(flavorArr, date, 703) : null;

  const reading = `PD ${pd} × ${tb.star} (${dp.ganzhi})`;
  return { line, flavor, reading };
}
