// 日付シード変異ピッカー
// 同じパーソナルデイでも別の日には異なるバリエーションを返す
// ==================================================================
export function dateSeed(date: Date, salt = 0): number {
  const k = date.getFullYear() * 10000 + (date.getMonth() + 1) * 100 + date.getDate();
  return ((k ^ (salt * 2654435761)) >>> 0);
}
export function pickByDate<T>(arr: readonly T[], date: Date, salt = 0): T {
  if (arr.length === 0) throw new Error("pickByDate: empty array");
  return arr[dateSeed(date, salt) % arr.length];
}

function digitSum(n: number): number {
  return String(n)
    .split("")
    .reduce((a, c) => a + Number(c), 0);
}
function reduce1to9(n: number): number {
  while (n > 9) n = digitSum(n);
  return n;
}

// ==== パーソナルデイ・パーソナルマンス ====
// パーソナルマンス = パーソナルイヤー + 当月
// パーソナルデイ = パーソナルマンス + 当日
export function personalMonth(birth: string, year: number, month: number): number {
  const [, m, d] = birth.split("-").map(Number);
  const py = reduce1to9(
    digitSum(m ?? 0) + digitSum(d ?? 0) + digitSum(year)
  );
  return reduce1to9(py + month);
}

export function personalDay(birth: string, year: number, month: number, day: number): number {
  const pm = personalMonth(birth, year, month);
  return reduce1to9(pm + day);
}

