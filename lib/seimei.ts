// 姓名判断（五格）
// 算出:
//   天格 = 姓の画数合計（祖運・先祖から受け継ぐ）
//   地格 = 名の画数合計（初年運・幼少〜青年）
//   人格 = 姓の最後の字 + 名の最初の字（中年運・性格の核）
//   外格 = 総格 − 人格（対人運・周囲との関わり）
//   総格 = 全体の画数合計（晩年運・人生総合）

export type Kakusu = {
  ten: number;   // 天格
  jin: number;   // 人格
  chi: number;   // 地格
  gai: number;   // 外格
  so: number;    // 総格
};

export function calcKakusu(seiKakusu: number[], meiKakusu: number[]): Kakusu {
  const ten = seiKakusu.reduce((a, b) => a + b, 0);
  const chi = meiKakusu.reduce((a, b) => a + b, 0);
  const so = ten + chi;
  const jin = (seiKakusu[seiKakusu.length - 1] ?? 0) + (meiKakusu[0] ?? 0);
  const gai = so - jin;
  return { ten, jin, chi, gai, so };
}

